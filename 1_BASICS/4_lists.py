# Declairing a list
nums = [10, 4,6,18,14, 420]

# Printing the list
print(nums)

# accessing a single value from the list
# indexing starts at 0 from the left
print(nums[0])
print(nums[1])

# indexing starts at -1 from the right
print(nums[-1])
print(nums[-2])

# you can store any type of value in a list
names = ["shohan", 'sagor', 'itvaya']

# you can access the value by indexing and store it in a variable
friend = names[1]

# you can use those values methods to modify the value
# You have to understand the datatype of that value in the list
print(friend.upper())

