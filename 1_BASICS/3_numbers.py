# Declairing a number
num = 10
num2 = 5

# +, -, *, / operators
print(num + num2)
print(num - num2)
print(num * num2)
print(num / num2)

# power operator
print(num ** num2)

# first multiply then add
print(2 * 3 + 4)

# first the calculate inside the parenthesis
print((2 + 3) * 4)

# Declairing a float
num = 10.0
print(num)

# some weird results you might get in float operations
print(3 * .1)

# Division will always return a float
print(15/5)

# you can declair multiple variables at the same time
num, num2, num3 = 10, 20, 30
print(num, num2, num3)

# you can use underscores to make numbers more readable
num = 1_000_000_000
print(num)

