# declairing a list
names = ['john doe', 'rishat', 'sohan', 'itvaya']

# starting a loop
# for variable in list:
for name in names:
    # have to put a tab before a command inside the loop
    print(f"welcome to the channel, {name.title()}")
    print(f"nice to meet you, {name.upper()}")
    
# anything outside the loop should not have a tab
print('the loop ended')

